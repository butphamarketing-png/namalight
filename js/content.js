NOMA.projectBySlug = function (s) {
  s = (s || '').toLowerCase();
  return NOMA.projects.filter(function (p) { return p.slug === s; })[0];
};

NOMA.articleBySlug = function (s) {
  s = (s || '').toLowerCase();
  return NOMA.articles.filter(function (p) { return p.slug === s; })[0];
};
